// melody), kick (soft brushed kick), snare (brush swish on 2 and 4), hat (ride, swung)]. Drum parts are unpitched:
// never transpose them. The 40-bar pass is 160 beats = 40 four-beat cycles (about 92.3 s at 104 BPM).
