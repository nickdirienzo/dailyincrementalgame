// changing notes or envelopes. createParts(S) returns [bass (sine tine bass), counter (sine bell), comb (triangle
// music-box melody)]. The revision's kick/snare/hat stems had no events and zero gain (a music box has no
// drums), so they are omitted. One 3/4 bar = 3 beats; the 48-bar pass is 144 beats = 36 four-beat cycles.
// slopwave score SHA-256: 0d68660132b695131e5e0da820923dd60a8c131314ddba9dfa792f0df51d0200
